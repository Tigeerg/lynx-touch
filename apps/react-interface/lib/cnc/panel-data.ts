// The machine manifest for the Qt port: tabs, workplaces, screens and the shared labels, rendered
// from the `lib/cnc` tables that React itself uses. QML reads the generated JavaScript module
// `apps/qt-interface/panel-data.js`; neither side keeps a hand copy of the words.
//
// The sets of F1..F8 are added when the workplace rule is ported (wave C): they need the machine
// state, so they are a separate export with their own check.
import { MODE_LABEL, SCREEN_LABEL, SOFTKEY_LABEL, WORKPLACE_LABEL } from './data'
import { MODES, MODE_START_SCREEN, SCREENS, TABS, TAB_LABEL, WORKPLACES } from './types'

const literal = (value: unknown): string => JSON.stringify(value, null, 2)

/** The text of `apps/qt-interface/panel-data.js`, a QML-compatible JavaScript module. */
export function renderPanelData(): string {
  return [
    '// Generated by lib/cnc/panel-data.ts. Do not edit by hand.',
    '//',
    '// The source is the React tables in lib/cnc; `pnpm test` compares this file with them.',
    '.pragma library',
    '',
    `var MODES = ${literal(MODES)}`,
    `var MODE_LABEL = ${literal(MODE_LABEL)}`,
    `var MODE_START_SCREEN = ${literal(MODE_START_SCREEN)}`,
    '',
    `var WORKPLACES = ${literal(WORKPLACES)}`,
    `var WORKPLACE_LABEL = ${literal(WORKPLACE_LABEL)}`,
    '',
    `var TABS = ${literal(TABS)}`,
    `var TAB_LABEL = ${literal(TAB_LABEL)}`,
    '',
    `var SCREENS = ${literal(SCREENS)}`,
    `var SCREEN_LABEL = ${literal(SCREEN_LABEL)}`,
    '',
    `var SOFTKEY_LABEL = ${literal(SOFTKEY_LABEL)}`,
    '',
  ].join('\n')
}
